DROP DATABASE IF EXISTS CLINICA;
CREATE DATABASE CLINICA CHARACTER SET UTF8MB4;
USE CLINICA;

CREATE TABLE CLIENTE(
	ID_CLIENTE INTEGER PRIMARY KEY,
	NOMBRE VARCHAR(50) NOT NULL,
	APELLIDO1 VARCHAR(50) NOT NULL,
	APELLIDO2 VARCHAR(50),
	POBLACION VARCHAR(45),
	DIRECCION VARCHAR(45),
	TELEFONO INTEGER(9) UNIQUE
);

CREATE TABLE MASCOTA(
	ID_MASCOTA INTEGER PRIMARY KEY,
	NOMBRE VARCHAR(50) NOT NULL,
	TIPO_ANIMAL VARCHAR(30) NOT NULL,
	RAZA VARCHAR(30),
	SEXO ENUM('M','F'),
	COLOR VARCHAR(30),
	ESTERILIZADO BOOLEAN DEFAULT FALSE,
	FECHA_NAC DATE,
	PESO INTEGER,
	ID_CLIENTE INTEGER,
	CONSTRAINT FK_MASCOTA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE TRATAMIENTO(
	ID_TRATAMIENTO INTEGER PRIMARY KEY,
	TIPO_TRATAMIENTO VARCHAR(50),
	PRECIO NUMERIC(5,2) CHECK(PRECIO <= 100)
);

CREATE TABLE VETERINARIO(
	ID_VETERINARIO INTEGER PRIMARY KEY,
	ID_VETERINARIO_ENCARGADO INTEGER,
	NOMBRE VARCHAR(50) NOT NULL,
	APELLIDO1 VARCHAR(50) NOT NULL,
	APELLIDO2 VARCHAR(50),
	TELEFONO INTEGER(9) UNIQUE
);

ALTER TABLE VETERINARIO ADD CONSTRAINT FK_VETERINARIO_VETERINARIO_ENCARGADO FOREIGN KEY (ID_VETERINARIO_ENCARGADO) REFERENCES VETERINARIO(ID_VETERINARIO) ON DELETE CASCADE ON UPDATE CASCADE;

CREATE TABLE ESPECIALIDAD(
	ID_ESPECIALIDAD INTEGER PRIMARY KEY,
	NOMBRE_ESPECIALIDAD VARCHAR(50) NOT NULL,
	GRADO VARCHAR(10) NOT NULL,
	CONSTRAINT CK_ESPECIALIDAD_GRADO CHECK (GRADO IN ('ALTO','MEDIO','BAJO'))
);

CREATE TABLE VETERINARIO_ESPECIALIDAD(
	ID_VETERINARIO INTEGER,
	ID_ESPECIALIDAD INTEGER,
	CONSTRAINT PK_VETERINARIO_ESPECIALIDAD PRIMARY KEY (ID_VETERINARIO, ID_ESPECIALIDAD),
	CONSTRAINT FK_VETERINARIO_ESPECIALIDAD_VETERINARIO FOREIGN KEY (ID_VETERINARIO) REFERENCES VETERINARIO(ID_VETERINARIO) ON DELETE CASCADE ON UPDATE CASCADE,
	CONSTRAINT FK_VETERINARIO_ESPECIALIDAD_ESPECIALIDAD FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES ESPECIALIDAD(ID_ESPECIALIDAD) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE VISITA_CLINICA(
	ID_VISITA_CLINICA CHAR(4),
	ID_VETERINARIO INTEGER NOT NULL,
	ID_MASCOTA INTEGER NOT NULL,
	FORMA_PAGO VARCHAR(50) NOT NULL,
	FECHA_PAGO DATE,
	FECHA_VISITA DATE NOT NULL,
	MOTIVO_VISITA VARCHAR(50) NOT NULL,
	ID_TRATAMIENTO INTEGER,
	CONSTRAINT PK_VISITA_CLINICA PRIMARY KEY (ID_VISITA_CLINICA),
	CONSTRAINT FK_VISITA_CLINICA_TRATAMIENTO FOREIGN KEY (ID_TRATAMIENTO) REFERENCES TRATAMIENTO(ID_TRATAMIENTO),
	CONSTRAINT FK_VISITA_CLINICA_VETERINARIO FOREIGN KEY (ID_VETERINARIO) REFERENCES VETERINARIO(ID_VETERINARIO),
	CONSTRAINT FK_VISITA_CLINICA_MASCOTA FOREIGN KEY (ID_MASCOTA) REFERENCES MASCOTA(ID_MASCOTA),
	CONSTRAINT CK_FORMA_PAGO CHECK (FORMA_PAGO IN ('TARJETA','EFECTIVO','PAYPAL','NO PAGADO'))
);

