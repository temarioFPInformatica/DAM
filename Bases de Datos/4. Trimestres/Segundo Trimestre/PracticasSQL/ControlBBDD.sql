use control1_bd;

CREATE TABLE A (
A1 VARCHAR(15),
A2 FLOAT(5,3) DEFAULT 2.4 CHECK (A2>=0 AND A2<=99.999),
A3 VARCHAR(1),
CONSTRAINT a_pk PRIMARY KEY (A1),
CONSTRAINT A3 CHECK (A3 IN ('H','M'))
);

CREATE TABLE B (
B1 VARCHAR(15),
B2 FLOAT(5,2)  DEFAULT 2.4 CHECK (B2>=0 AND B2<=99.999),
B3 VARCHAR(1),
CONSTRAINT b_PK PRIMARY KEY (B1),
CONSTRAINT B3 CHECK (B3 IN ('H','M'))
);

CREATE TABLE R (
A1 VARCHAR(15),
B1 VARCHAR(15),
R1 VARCHAR(15),
CONSTRAINT A1_FK1 FOREIGN KEY (A1) REFERENCES A(A1),
CONSTRAINT B1_FK2 FOREIGN KEY (B1) REFERENCES B(B1)
);
